// Refreshes assets/ from the landing page (../LANDING PAGE), so the one-pager shows the same
// fonts and pictures as the site:
//   1. copies the two fonts and the pictures it uses;
//   2. takes the hero tablet's screen out of the landing page as one SVG, so its recording stays
//      vector in the PDF. The PDF shows measurements, never a reading, so the copy drops the axis
//      and rhythm verdicts ("Normal axis", "Regular"), the normal-range sector and the red ST
//      marks. Sora is embedded in the SVG, which an <img> cannot load from outside;
//   3. sizes the hand for print (about 300 dpi at its size on the sheet), so the PDF stays
//      small enough to send.
// usage: node tools/assets.mjs [landing-url]     (default: the live site)
// Borrows puppeteer-core from ../LANDING PAGE/node_modules; drives the installed Chrome.
import { createRequire } from "node:module";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LANDING = join(ROOT, "..", "LANDING PAGE");
const SRC = join(LANDING, "src", "assets");
const OUT = join(ROOT, "assets");
const require = createRequire(join(LANDING, "package.json"));
const puppeteer = require("puppeteer-core");
const CHROME = process.env.CHROME || "C:/Program Files/Google/Chrome/Application/chrome.exe";
const URL = process.argv[2] || "https://cyphix-landing.vercel.app/";

// published name → the landing page's file
const COPY = {
  "fonts/sora-latin-var.woff2": "fonts/sora-latin-var.woff2",
  "fonts/geist-mono-latin-var.woff2": "fonts/geist-mono-latin-var.woff2",
  "img/tablet-frame.webp": "img/tablet-frame.webp",
  "img/portrait-elio.webp": "img/portrait-elio.webp",
  "img/portrait-tamir.webp": "img/portrait-tamir.webp",
};
// published name → [the landing page's file, height in px for print]
const SHRINK = {
  "img/hero-wrist.png": ["photos/hero-wrist.webp", 1280],
};
for (const [to, from] of Object.entries(COPY)) {
  mkdirSync(dirname(join(OUT, to)), { recursive: true });
  copyFileSync(join(SRC, from), join(OUT, to));
}

const browser = await puppeteer.launch({ executablePath: CHROME, headless: "new" });
const page = await browser.newPage();

// 2. the tablet's screen, as the hero draws it (static), less its readings
await page.setViewport({ width: 1440, height: 900 });
await page.goto(URL, { waitUntil: "networkidle0" });
const screen = await page.evaluate(() => {
  const s = document.querySelector(".hero .hero-system-screen").cloneNode(true);
  const verdicts = ["Normal axis", "RHYTHM", "Regular"];
  s.querySelectorAll("text").forEach((t) => {
    const v = t.textContent.trim();
    if (verdicts.includes(v) || v.startsWith("Shaded sector")) t.remove();
  });
  s.querySelectorAll('path[fill="#e6ecf5"]').forEach((p) => p.remove()); // the normal-range sector
  s.querySelectorAll('path[stroke="#e0352b"]').forEach((p) => p.remove()); // the red ST marks
  s.querySelectorAll('rect[y="670"]').forEach((r) => r.remove()); // the rhythm's divider
  s.querySelector('rect[y="555.5"]')?.setAttribute("height", "118"); // the heart rate's card, without the rhythm
  for (const a of ["class", "role", "aria-label"]) s.removeAttribute(a);
  s.setAttribute("xmlns", "http://www.w3.org/2000/svg");
  s.setAttribute("width", "1330");
  s.setAttribute("height", "888");
  return new XMLSerializer().serializeToString(s);
});
if (/Normal axis|Regular|#e0352b/.test(screen)) throw new Error("the tablet's screen still carries a reading");
const sora = readFileSync(join(SRC, "fonts", "sora-latin-var.woff2")).toString("base64");
const style =
  `<style>@font-face{font-family:Sora;src:url(data:font/woff2;base64,${sora}) format("woff2");font-weight:100 800}` +
  `svg{font-family:Sora,sans-serif}</style>`;
writeFileSync(
  join(OUT, "img", "tablet-screen.svg"),
  screen.replace(/^<svg[^>]*>/, (open) => open + style) +
    "\n<!-- v1.0.0 — generated by tools/assets.mjs: the landing page's hero tablet screen, without its readings -->\n",
);

// 3. the cut-outs, at print size, transparency kept
for (const [to, [from, height]] of Object.entries(SHRINK)) {
  const src = readFileSync(join(SRC, from)).toString("base64");
  await page.setContent(`<img id="s" src="data:image/webp;base64,${src}">`);
  const png = await page.evaluate(async (height) => {
    const img = document.getElementById("s");
    await img.decode();
    const c = document.createElement("canvas");
    c.height = height;
    c.width = Math.round((img.naturalWidth * height) / img.naturalHeight);
    const x = c.getContext("2d");
    x.imageSmoothingQuality = "high";
    x.drawImage(img, 0, 0, c.width, c.height);
    return c.toDataURL("image/png").split(",")[1];
  }, height);
  writeFileSync(join(OUT, to), Buffer.from(png, "base64"));
}

await browser.close();
console.log("assets refreshed from", URL);

